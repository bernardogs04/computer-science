class Data{
	private int ano;
	private int mes;
	private int dia;

	public int getAno(){
		return ano;
	}
	public int getMes(){
		return mes;
	}
	public int getDia(){
		return dia;
	}
	public int setAno(int a){
		ano = a;
	}
	public int setMes(int a){
		mes = a;
	}
	public int setDia(int a){
		dia = a;
	}
}
